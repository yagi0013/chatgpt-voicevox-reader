async function testPlayer() {
  for (const [length, expected] of [[0,1], [1,1], [50,1], [51,1.15], [100,1.15], [101,1.30], [200,1.30], [201,1.45], [300,1.45], [301,1.60], [1000,1.60]]) {
    if (speechRate('あ'.repeat(length)) !== expected) throw new Error('speech rate boundary: ' + length);
  }
  if (speechRate('あ'.repeat(50) + ' \n\t') !== 1) throw new Error('whitespace excluded');
  if (speechRate('𠮷'.repeat(50)) !== 1) throw new Error('unicode code points');
  const wait = () => new Promise(resolve => setTimeout(resolve, 0));
  const send = message => new Promise(resolve => listener({target: 'player', ...message}, {}, resolve));
  const item = {name: 'ずんだもん', styleId: 3, text: 'テスト'};
  await send({type: 'QUEUE', tabId: 1, batchId: 'first', items: [item, item]});
  await send({type: 'QUEUE', tabId: 1, batchId: 'first', items: [item, item]});
  for (let i = 0; i < 15; i++) await wait();
  if (played !== 2) throw new Error('queue order/dedup: ' + played);
  if (requests.length !== 4 || !requests[0].includes('audio_query') || !requests[1].includes('synthesis')) throw new Error('query before synthesis');
  holdAudio = true;
  await send({type: 'QUEUE', tabId: 1, batchId: 'second', items: [item, item]});
  for (let i = 0; i < 10; i++) await wait();
  const panelStatus = await send({type: 'STATUS', tabId: 1});
  if (panelStatus.speaker !== item.name || panelStatus.styleId !== item.styleId || !panelStatus.active) throw new Error('panel speaker metadata');
  if (panelStatus.duration !== 0 || panelStatus.elapsed !== 0) throw new Error('unknown media duration is finite');
  await send({type: 'STOP', tabId: 1});
  for (let i = 0; i < 10; i++) await wait();
  const stopped = await send({type: 'STATUS', tabId: 1});
  if (stopped.pending !== 0 || stopped.status !== '停止しました') throw new Error('stop clears queue');
  holdAudio = false;
  failFetch = true;
  await send({type: 'QUEUE', tabId: 2, batchId: 'error', items: [item, item]});
  for (let i = 0; i < 10; i++) await wait();
  const error = await send({type: 'STATUS', tabId: 2});
  if (!error.status.startsWith('エラー') || error.pending) throw new Error('error status/queue');
  failFetch = false;
  const before = played;
  await send({type: 'QUEUE', tabId: 2, batchId: 'recovery', items: [item]});
  for (let i = 0; i < 10; i++) await wait();
  if (played !== before + 1) throw new Error('recovery after stop/error');
  const longItem = {...item, text: 'あ'.repeat(301)};
  await send({type: 'QUEUE', tabId: 2, batchId: 'long-speech', items: [longItem]});
  for (let i = 0; i < 10; i++) await wait();
  const query = synthesisQueries.at(-1);
  if (query.speedScale !== 1.60 || query.pitchScale !== 0.15) throw new Error('synthesis speed and pitch preservation');
  await send({type: 'QUEUE', tabId: 2, batchId: 'styled-speech', items: [{name: '四国めたん', styleId: 6, text: 'ツンツンのテスト'}]});
  for (let i = 0; i < 10; i++) await wait();
  if (!requests.at(-2).includes('speaker=6') || !requests.at(-1).includes('speaker=6')) throw new Error('selected style must reach both engine endpoints');
  await send({type: 'QUEUE', tabId: 2, batchId: 'dictionary-emotion', items: [{...item, text: '春雨！！', speechText: 'はるさめ！！'}]});
  for (let i = 0; i < 10; i++) await wait();
  if (!requests.at(-2).includes(encodeURIComponent('はるさめ！！')) || synthesisQueries.at(-1).speedScale !== 1.04) throw new Error('dictionary and emotion must reach engine');
  await send({type: 'QUEUE', tabId: 2, batchId: 'explicit-style-emotion', items: [{...item, text: '春雨！！', requestedStyle: 'あまあま'}]});
  for (let i = 0; i < 10; i++) await wait();
  if (synthesisQueries.at(-1).speedScale !== 1 || synthesisQueries.at(-1).pitchScale !== 0.15) throw new Error('explicit style bypasses emotion');
  audioOutputId = 'headphones';
  await send({type: 'QUEUE', tabId: 2, batchId: 'output-selected', items: [item]});
  for (let i = 0; i < 10; i++) await wait();
  if (sinks.at(-1) !== 'headphones') throw new Error('saved output must be applied');
  const beforeMissing = played;
  failSink = true;
  await send({type: 'QUEUE', tabId: 2, batchId: 'output-missing', items: [item, item]});
  for (let i = 0; i < 10; i++) await wait();
  const missing = await send({type: 'STATUS', tabId: 2});
  if (played !== beforeMissing + 2 || missing.pending || missing.status !== '待機中' || sinks.at(-1) !== '') throw new Error('missing output must fall back and preserve queue');
  if (audioOutputId !== 'headphones') throw new Error('fallback must preserve saved preference');
  failSink = false;
  holdAudio = true;
  await send({type: 'QUEUE', tabId: 2, batchId: 'output-restored', items: [item]});
  for (let i = 0; i < 10; i++) await wait();
  if (sinks.at(-1) !== 'headphones') throw new Error('next playback must restore preferred output');
  const playingAudio = current.audio;
  playingAudio.currentTime = 2;
  const changed = await send({type: 'OUTPUT_CHANGED', audioOutputId: 'speakers'});
  if (!changed.ok || sinks.at(-1) !== 'speakers' || current.audio !== playingAudio || current.audio.currentTime !== 2) throw new Error('live setting change must preserve audio position');
  await send({type: 'OUTPUT_CHANGED', audioOutputId: 'headphones'});
  failSink = true;
  deviceChange();
  for (let i = 0; i < 10; i++) await wait();
  if (sinks.at(-1) !== '') throw new Error('disconnect during playback must use default');
  const fallbackStatus = await send({type: 'STATUS', tabId: 2});
  if (!fallbackStatus.outputWarning || !fallbackStatus.status.includes('既定で再生中')) throw new Error('fallback reason must be visible');
  failSink = false;
  deviceChange();
  deviceChange();
  for (let i = 0; i < 10; i++) await wait();
  if (sinks.at(-1) !== 'headphones') throw new Error('reconnect during playback must restore preferred output');
  if ((await send({type: 'STATUS', tabId: 2})).outputWarning) throw new Error('recovery must clear warning');
  await send({type: 'STOP', tabId: 2});
  for (let i = 0; i < 10; i++) await wait();
  holdAudio = false;
  audioOutputId = '';
  await send({type: 'QUEUE', tabId: 2, batchId: 'output-default', items: [item]});
  for (let i = 0; i < 10; i++) await wait();
  if (played !== beforeMissing + 4) throw new Error('system default must recover');
  holdAudio = true;
  await send({type: 'QUEUE', tabId: 10, batchId: 'controls', items: [item, {...item, text: '次'}, {...item, text: '最後'}]});
  for (let i = 0; i < 10; i++) await wait();
  const originalAudio = current.audio;
  originalAudio.currentTime = 1.5;
  const beforePause = played;
  await send({type: 'PAUSE', tabId: 10});
  const paused = await send({type: 'STATUS', tabId: 10});
  if (!paused.paused || !paused.active || paused.pending !== 2) throw new Error('pause must preserve active speech and queue');
  await send({type: 'RESUME', tabId: 10});
  if (current.audio !== originalAudio || current.audio.currentTime !== 1.5 || played !== beforePause + 1) throw new Error('resume must use same audio and playback position');
  await send({type: 'SKIP', tabId: 10});
  for (let i = 0; i < 10; i++) await wait();
  if (current.audio === originalAudio || queue.filter(job => job.tabId === 10).length !== 1) throw new Error('skip must advance exactly one speech');
  await send({type: 'PAUSE', tabId: 10});
  await send({type: 'SKIP', tabId: 10});
  for (let i = 0; i < 10; i++) await wait();
  const pausedSkip = await send({type: 'STATUS', tabId: 10});
  if (!pausedSkip.paused || pausedSkip.active || pausedSkip.pending !== 1) throw new Error('skip while paused must preserve pause and next speech');
  await send({type: 'QUEUE', tabId: 11, batchId: 'other-tab', items: [item]});
  for (let i = 0; i < 10; i++) await wait();
  if (current.tabId !== 11) throw new Error('paused queue must not block another tab');
  await send({type: 'STOP', tabId: 10});
  if (current.tabId !== 11 || current.controller.signal.aborted || (await send({type: 'STATUS', tabId: 10})).pending) throw new Error('cancel must isolate target tab');
  await send({type: 'STOP', tabId: 11});
  for (let i = 0; i < 10; i++) await wait();
  const realFetch = fetch;
  let releaseSynthesis;
  fetch = async (url, options) => {
    if (url.includes('/synthesis?')) await new Promise(resolve => { releaseSynthesis = resolve; });
    return realFetch(url, options);
  };
  await send({type: 'QUEUE', tabId: 12, batchId: 'pause-synthesis', items: [item, item]});
  for (let i = 0; i < 10; i++) await wait();
  await send({type: 'PAUSE', tabId: 12});
  const beforeSynthesis = played;
  releaseSynthesis();
  for (let i = 0; i < 10; i++) await wait();
  if (played !== beforeSynthesis || !(await send({type: 'STATUS', tabId: 12})).paused) throw new Error('pause during synthesis must prevent playback');
  await send({type: 'RESUME', tabId: 12});
  if (played !== beforeSynthesis + 1) throw new Error('synthesized paused speech must resume');
  await send({type: 'STOP', tabId: 12});
  for (let i = 0; i < 10; i++) await wait();
  fetch = realFetch;
  const cancelled = await send({type: 'STATUS', tabId: 12});
  if (cancelled.active || cancelled.paused || cancelled.pending) throw new Error('cancel clears active, pause and queue');
  await send({type: 'QUEUE', tabId: 13, batchId: 'rapid-skip', items: [item, item, item]});
  for (let i = 0; i < 10; i++) await wait();
  skipPlayback(13);
  skipPlayback(13);
  for (let i = 0; i < 10; i++) await wait();
  if (queue.some(job => job.tabId === 13) || current?.tabId !== 13) throw new Error('rapid skips must consume distinct speeches');
  await send({type: 'STOP', tabId: 13});
  for (let i = 0; i < 10; i++) await wait();
  holdAudio = false;
  print('PASS: playback pause/resume position, skip, paused skip, tab isolation, cancel and pause during synthesis');
  print('PASS: saved audio output, temporary fallback, queue continuity, live disconnect/reconnect, preferred output recovery');
  print('PASS: player FIFO, batch dedup, stop, error, recovery, speech rate boundaries and synthesis payload');
}
const loop = new GLib.MainLoop(null, false);
testPlayer().then(() => loop.quit(), error => { printerr(error.stack); failure = true; loop.quit(); });
